"""Sphinx configuration for the Pravrudhi code documentation.

Built by `make html` in this folder (the CI job `docs` runs the same command). Everything under `api/` is read
from the code's own docstrings; `narrative/` and `reference/` are written (reference/ is generated by
`gen_reference.py` and checked for drift in CI).
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "pravrudhi_kernel" / "src"))

project = "Pravrudhi"
author = "Axis Meru"
copyright = "Axis Meru, Apache-2.0"

try:  # one source for the version: the installed package metadata
    from importlib.metadata import version as _v

    release = _v("pravrudhi")
except Exception:  # pragma: no cover - building from a bare checkout
    release = "unknown"
version = release

extensions = [
    "sphinx.ext.autodoc",
    "sphinx.ext.autosummary",
    "sphinx.ext.napoleon",
    "sphinx.ext.viewcode",
    "sphinx.ext.intersphinx",
    "sphinx.ext.todo",
    "sphinx_autodoc_typehints",
    "myst_parser",
]

# The hosted copy leaves out the "[source]" pages (full source listings): the signatures and docstrings are the documentation.
if os.environ.get("PRAVRUDHI_DOCS_NO_SOURCE_PAGES"):
    extensions.remove("sphinx.ext.viewcode")

source_suffix = {".rst": "restructuredtext", ".md": "markdown"}
master_doc = "index"
exclude_patterns = ["_build", "Thumbs.db", ".DS_Store"]
templates_path: list[str] = []

# The reference pages are plain markdown tables; allow heading anchors and tables.
myst_heading_anchors = 3
myst_enable_extensions = ["colon_fence"]

autodoc_default_options = {
    "members": True,
    "undoc-members": True,
    "show-inheritance": True,
    "member-order": "bysource",
}
# Show a default as written in the source (a name), not its evaluated value: evaluated values leak local paths and constants.
autodoc_preserve_defaults = True
autodoc_typehints = "description"
autodoc_typehints_format = "short"
autosummary_generate = True
add_module_names = False

# The docstrings are prose with backticks; Google style is accepted where used, numpy style is not used.
napoleon_google_docstring = True
napoleon_numpy_docstring = False

# Defensive backstop: optional or heavy dependencies that may not be installed on a docs runner. Nothing at
# module scope imports them today; the list keeps a later import from breaking the docs build.
autodoc_mock_imports = [
    "torch",
    "transformers",
    "peft",
    "trl",
    "unsloth",
    "pg8000",
    "pypdfium2",
    "PIL",
]

intersphinx_mapping = {"python": ("https://docs.python.org/3", None)}
todo_include_todos = False

# Docstring prose is not always valid reST (backticks, bare asterisks); those are style, not build errors.
suppress_warnings = ["sphinx_autodoc_typehints.forward_reference", "ref.python", "autosummary.import_cycle"]

html_theme = "sphinx_rtd_theme"
html_static_path = ["_static"]
html_css_files = ["custom.css"]
html_title = f"Pravrudhi {release}"


def _skip_private_values(app, what, name, obj, skip, options):  # type: ignore[no-untyped-def]
    """Leave out module data that carries a private identifier or a local path in its value."""
    if skip or what != "module":
        return skip
    if name.startswith(("PRIVATE", "DROP_", "INTERNAL_")) or name.endswith(("_MARKERS", "_PATTERNS")):
        return True
    try:
        text = repr(obj)
    except Exception:  # pragma: no cover - an object whose repr fails is left as autodoc decided
        return skip
    return True if ("/home/" in text or "fusion-project" in text) else skip


def setup(app) -> None:  # type: ignore[no-untyped-def]
    app.connect("autodoc-skip-member", _skip_private_values)
